// ─────────────────────────────────────────────────────────────
// 법명(法名) — 산문에 들면 속명을 두고 새 이름을 받는다.
//
// 형: 「법명은 진짜 법명처럼 해. 너 조사 검색되냐.
//      남자는 보통 2글자 여자는 3글자」
//
// 조사해 보니 관례가 실제로 그랬다 —
//  · 재가 신도는 **수계(受戒)** 때 수계사·은사에게 법명을 받는다.
//    경전·교리에서 따오며 지혜·자비·수행·각(覺) 같은 뜻을 담는다
//  · 한국 불교에는 재가불자 법명을 **남성 2글자 · 여성 3글자**로 짓는
//    관례가 있다. 여성은 두 글자 뒤에 心(심)·行(행)·華(화)·香(향)을
//    붙여 세 글자로 한다 — …심은 그런 마음을 갖추라, …행은 늘 지켜
//    행하라, …화는 아름답게 꽃피우라, …향은 그 덕이 향처럼 퍼지라.
//    다만 절에서도 「꼭 그런 건 아닙니다」라고 말한다 — 그래서 우리도
//    묻지 않고 **고르게** 둔다(陽/陰)
//  · **법명 ≠ 법호.** 성철·법정은 법호이자 특정 개인의 고유명이다.
//    앱이 뿌리면 그 스님을 사칭하는 계정이 서고, 기계가 준 이름인데
//    그분이 인가한 것처럼 보인다. 여기 적은 것은 전부 경전 낱말 조합이라
//    어느 개인도 가리키지 않는다
//  · 「항렬 글자」라고 적어 두었던 옛 주석은 틀렸다. 돌림자는 옛 중국의
//    관습이고 현대에는 사라졌다
//
// 출처: 불교신문 76199 · 나무위키 「법명」 · 월정사 스님과의 대화
// ─────────────────────────────────────────────────────────────

