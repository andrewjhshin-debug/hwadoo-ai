export const LEARN_KEY = "hwadu.learn.v1";

export function loadLearned(): string[] {
  try {
    const v = JSON.parse(localStorage.getItem(LEARN_KEY) || "[]");
    return Array.isArray(v) ? v : [];
  } catch {
    return [];
  }
}

export function markLearned(id: string): string[] {
  const list = loadLearned();
  if (list.includes(id)) return list;
  const next = [...list, id];
  try { localStorage.setItem(LEARN_KEY, JSON.stringify(next)); } catch { /* 막혀도 배운 건 배운 것 */ }
  return next;
}
