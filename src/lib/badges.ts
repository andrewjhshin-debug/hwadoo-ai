// ─────────────────────────────────────────────────────────────
// 걸음 — 얻은 자리(뱃지). 화두를 몇 번 회향했나로 오른다.
// 내 도량의 뱃지 격자와 사이드바의 한 글자 뱃지가 같은 임계값을 쓴다.
//
// ■ 육도(六道)에서 십우도(十牛圖)로 옮긴 까닭
//   전에는 인간도(1) → 수라도(5) → 천상도(15) 였다. 두 가지가 어긋났다.
//
//   ① 앱 안에서 서열이 둘이었다. realm.ts 의 육도는 수라도(21,600) 아래,
//      인간도(84,000) 위다 — 경전 순서(지옥·아귀·축생·수라·인간·천상)대로다.
//      그런데 여기서는 인간도 위에 수라도가 있었다. 같은 여섯 길을 두고
//      앱이 서로 다른 순서를 가르치고 있었다.
//   ② 애초에 육도는 **오르는 사다리가 아니다.** 벗어나야 할 굴레이고,
//      목표는 천상도가 아니라 그 밖(해탈)이다. 천상도조차 복이 다하면
//      떨어진다(天人五衰). 게다가 첫 자리가 「수라」면 앱이 사람을
//      아수라라고 부르는 셈이다.
//
//   그래서 십우도(十牛圖)의 앞 세 폭을 빌렸다. 소를 찾아 나서고(尋牛),
//   자취를 보고(見跡), 마침내 소를 본다(見牛) — 셋 다 **깨닫기 전**의
//   그림이라 「화두 열다섯 개 풀었으니 견성」 같은 말이 안 된다.
//   한국 절 벽화로 다들 본 그림이고, 화두를 드는 앱에 이보다 맞는 자가 없다.
//
// 뒷방 주인은 늘 마지막 자리 — 도량 주인의 자리.
// ─────────────────────────────────────────────────────────────

import { isAdminAccount } from "./config";

export const BADGES = [
  { hanja: "尋", name: "심우", full: "尋牛", need: 1, cond: "첫 회향" },
  { hanja: "跡", name: "견적", full: "見跡", need: 5, cond: "회향 5 이상" },
  { hanja: "牛", name: "견우", full: "見牛", need: 15, cond: "회향 15 이상" },
] as const;

// 걸음 뱃지 — 회향 수로 오른 자리 중 최고 한 글자. 회향이 없으면 null.
export function rankHanja(returned: number): string | null {
  for (let i = BADGES.length - 1; i >= 0; i--) {
    if (returned >= BADGES[i].need) return BADGES[i].hanja;
  }
  return null;
}

// 계정을 함께 살피는 판 — 뒷방 주인이면 회향 수와 무관하게 마지막 자리.
export function rankHanjaFor(
  returned: number,
  u?: { uid?: string | null; email?: string | null } | null
): string | null {
  if (isAdminAccount(u)) return "牛";
  return rankHanja(returned);
}
