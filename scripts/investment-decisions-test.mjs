import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
import { createRequire } from "node:module";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
const require = createRequire(import.meta.url);
function load(file) {
  const exports = {};
  const js = ts.transpileModule(fs.readFileSync(file, "utf8"), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX } }).outputText;
  new Function("require", "exports", js)(require, exports); return exports;
}
const m = load("src/lib/investment-decisions.ts"), now = Date.now();
const rules = ["이유를 적기", "한 번 쉬기", "남과 비교하지 않기"];
const draft = { ...m.DEFAULT_DECISION_DRAFT, name: "내 판단", reason: "내가 확인한 사실", invalidation: "반대 근거가 생기면 다시 본다", pauseUntil: now - 1 };
const first = m.makeDecision(draft, rules, now, "decision-one");
rules[0] = "바꾼 원칙";
assert.equal(first.principles[0], "이유를 적기", "original principles are immutable snapshots");
assert.equal(first.pauseSeconds, 108); assert.equal(first.review, null);
assert.equal(first.revisitAt, now + 86400000);
assert.throws(() => m.makeDecision({ ...draft, reason: "  " }, rules, now, "invalid"));
const store = new Map([["hwadu.tamjinchi.v1", "legacy-journal-do-not-touch"], ["hwadu.investment.rules.v1", "legacy-rules-do-not-touch"]]);
const storage = { getItem: key => store.get(key) ?? null, setItem: (key, value) => store.set(key, value) };
let book = m.addDecision(m.readDecisionBook(storage), first);
m.writeDecisionBook(book, storage);
assert.deepEqual(m.readDecisionBook(storage), book);
assert.equal(m.decisionStats(book, now + 1000).due, 0);
assert.equal(m.decisionStats(book, now + 86400001).due, 1);
assert.equal(m.decisionStats(book, now).keptRate, null, "empty sample must not invent a success rate");
const before = JSON.stringify(first);
book = m.reviewDecision(book, first.id, { at: now + 86400002, action: "wait", rules: "partly", intensity: 2, note: "다음엔 미리 쉬기" });
assert.equal(JSON.stringify(first), before, "review must not mutate the before record");
assert.equal(book.records[0].reason, draft.reason);
assert.equal(m.decisionStats(book, now + 86400003).reviewed, 1);
assert.equal(m.decisionStats(book, now + 86400003).keptRate, 0, "partial compliance is not counted as full compliance");
assert.throws(() => m.reviewDecision(book, "missing", book.records[0].review));
assert.throws(() => m.reviewDecision(book, first.id, { ...book.records[0].review, at: now - 1 }));
const second = m.makeDecision({ ...draft, pauseUntil: now + 100000 }, rules, now + 1000, "decision-two");
assert.equal(second.pauseSeconds, 0, "unfinished pause cannot be recorded as complete");
const merged = m.mergeDecisionBackup(book, { version: 2, records: [first, second] });
assert.equal(merged.records.length, 2); assert(merged.records.find(r => r.id === first.id).review, "old backup cannot overwrite current review");
for (const bad of [null, {}, { version: 1, records: [] }, { version: 2, records: [{ ...first, intensity: 11 }] }, { version: 2, records: [{ ...first, mood: "__proto__" }] }, { version: 2, records: [first, first] }, { version: 2, records: [{ ...first, reason: "x".repeat(501) }] }]) assert.throws(() => m.parseDecisionBook(bad));
const full = { version: 2, records: Array.from({ length: 500 }, (_, i) => ({ ...first, id: `limit-${i}`, at: now - i })) };
assert.throws(() => m.addDecision(full, second));
const preserved = store.get(m.DECISIONS_KEY);
assert.throws(() => m.writeDecisionBook(merged, { ...storage, setItem: () => { throw new Error("quota"); } }), /저장하지 못했어요/);
assert.equal(store.get(m.DECISIONS_KEY), preserved);
store.set(m.DECISIONS_KEY, "broken-json");
assert.throws(() => m.readDecisionBook(storage), /덮어쓰지 않았어요/);
assert.equal(store.get(m.DECISIONS_KEY), "broken-json");
assert.equal(store.get("hwadu.tamjinchi.v1"), "legacy-journal-do-not-touch");
assert.equal(store.get("hwadu.investment.rules.v1"), "legacy-rules-do-not-touch");
const art = load("src/components/InvestmentDancheong.tsx");
const chart = renderToStaticMarkup(React.createElement(art.InvestmentChartMark));
assert.equal((chart.match(/<rect/g) ?? []).length, 3);
assert(chart.includes("polyline") && chart.includes("#3d8877") && chart.includes("#c66f62"));
const page = fs.readFileSync("src/app/tamjinchi/page.tsx", "utf8");
assert(!page.includes("<InvestmentPractice") && !page.includes("세 번, 툭"));
assert(page.includes("이전 참회록") && page.includes("DECISION_DRAFT_KEY"));
console.log("PASS: plan/review lifecycle, due dates, immutable original reasons/rules, real-only stats, unfinished pause, backup merge/validation/limits, quota/corrupt storage preservation, legacy preservation, three-candle dancheong mark");
