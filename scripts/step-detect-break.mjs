// 걸음 모양·중력·잡음 틀은 check 와 같게 뒀다(같은 세계에서 깨뜨려야 공정하다).
import { createStepDetector } from "../src/lib/stepDetect.ts";

const HZ = 50;
const DT = 1000 / HZ;

function rng(seed) {
  let s = seed >>> 0;
  return () => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    return s / 4294967296;
  };
}
const 잡음 = (r, 폭) => (r() + r() + r() - 1.5) * 폭 * 1.6;

const 방향 = (v) => {
  const n = Math.hypot(...v);
  return v.map((c) => c / n);
};
const 중력A = 방향([0.35, 0.8, 0.49]).map((c) => c * 9.81); // 손에 들고 화면 보기
const 중력B = 방향([0.1, -0.95, 0.3]).map((c) => c * 9.81); // 주머니 — 거꾸로 꽂힘

/** f(t초, r) → { a:[x,y,z](중력 없는 충격), g:[gx,gy,gz](중력, 없으면 중력A) } 또는 [x,y,z] */
function 돌리기(초, f, { seed = 7, 표본간격 = () => DT, d = null, t0 = 0, 끊김한번 = false } = {}) {
  const r = rng(seed);
  let 센 = 0;
  let 최대한번 = 0;
  const det = d ?? createStepDetector({ onStep: (n) => { 센 += n; 최대한번 = Math.max(최대한번, n); } });
  let t = t0;
  const 끝 = t0 + 초 * 1000;
  while (t < 끝) {
    const out = f((t - t0) / 1000, r);
    const a = Array.isArray(out) ? out : out.a;
    const g = Array.isArray(out) ? 중력A : out.g ?? 중력A;
    det.feed(g[0] + a[0], g[1] + a[1], g[2] + a[2], t);
    t += 표본간격(r);
    if (끊김한번 && t - t0 >= 6000 && t - t0 < 6000 + DT) t += 1000;
  }
  return { 센, 최대한번, det };
}

/** 걸음 충격 — check 와 같은 모양. 위 = 중력 방향(기본 중력A). 진폭함수로 좌우 비대칭을 줄 수 있다 */
function 걷기(hz, 진폭, 잡음폭, 걸음수, { 시작 = 0.5, 간격흔들림 = 0.06, 세기흔들림 = 0.15, 위 = 방향(중력A), 진폭함수 = null, seed = 99 } = {}) {
  const 간격 = 1 / hz;
  const 걸음들 = [];
  let t = 시작;
  const r0 = rng(seed);
  for (let i = 0; i < 걸음수; i++) {
    const base = 진폭함수 ? 진폭함수(i) : 진폭;
    걸음들.push({ t, a: base * (1 - 세기흔들림 + r0() * 2 * 세기흔들림) });
    t += 간격 * (1 - 간격흔들림 + r0() * 2 * 간격흔들림);
  }
  const 끝 = t + 1.5;
  const f = (t, r) => {
    let p = 0;
    for (const s of 걸음들) {
      const u = t - s.t;
      if (u >= 0 && u < 0.12) p += s.a * Math.sin((u / 0.12) * Math.PI);
      else if (u >= 0.12 && u < 0.24) p -= 0.4 * s.a * Math.sin(((u - 0.12) / 0.12) * Math.PI);
    }
    return [위[0] * p + 0.15 * p + 잡음(r, 잡음폭), 위[1] * p + 잡음(r, 잡음폭), 위[2] * p - 0.1 * p + 잡음(r, 잡음폭)];
  };
  return { f, 끝, 걸음들 };
}

function 떨림(진폭) {
  let 위상 = 0;
  let hz = 10;
  return (t, r) => {
    hz += (r() - 0.5) * 1.5;
    hz = Math.min(12, Math.max(8, hz));
    위상 += (2 * Math.PI * hz) / HZ;
    const a = 진폭 * (0.6 + r() * 0.8);
    return [a * Math.sin(위상), a * 0.5 * Math.cos(위상 * 1.3), 잡음(r, 0.02)];
  };
}

